import { SITE } from '../site'

export function About({ onBack }: { onBack?: () => void }) {
  return (
    <section className="card about">
      {onBack && <button onClick={onBack}>戻る</button>}
      <h1>{SITE.name} について</h1>
      <p>自分のNostrの投稿とタイムラインから、自分をネタにして遊ぶ非公式のアプリです。</p>

      <h2>データの保存先</h2>
      <ul>
        <li>取得した投稿、分析結果、APIキーは、お使いのブラウザの中にだけ保存します。</li>
        <li>このアプリには運営者のサーバーがなく、運営者があなたのデータを見ることはできません。</li>
        <li>アクセス解析やCookieは使っていません。</li>
        <li>入力するのは公開鍵(npub)だけです。秘密鍵(nsec)は入力しないでください。</li>
      </ul>

      <h2>通信先</h2>
      <ul>
        <li>投稿の取得のため、Nostrのリレーに接続します。設定の基本のリレーと、各自のリレーリストにあるリレーです。</li>
        <li>AI分析を実行すると、抽出した投稿と質問を、設定で選んだAIの会社へ送ります。その際のデータの扱いは各社の規約に従います。</li>
        <li>結果をNostrに共有すると、紙面の画像を選んだ画像サーバー(Primal または nostr.build)にアップロードし、本文と画像のURLを自分のリレーと基本のリレーに投稿します。共有はボタンを押して署名したときだけ行います。</li>
        <li>カスタムAPIを選ぶと、AIの会社ではなく、設定したURLへ送ります。このPCで動かしている場合、投稿はPCの外に出ません。</li>
        <li>新聞、流され度診断、TL天気予報、一部の自由質問では、文脈としてフォロー中の人の投稿も送ります。実行前の確認画面で件数を確認できます。</li>
        <li>その際、投稿者の名前や公開鍵は送らず、本文中のフォロー中の人の名前も伏せます。短い名前やフォロー外の人の名前は残ることがあります。</li>
        <li>分析の対象は本人だけで、他の人を診断しないようAIに指示しています。</li>
      </ul>

      <h2>AI分析の費用</h2>
      <ul>
        <li>AI分析にはご自身のAPIキーが必要で、費用はキーの持ち主が各社に支払います。カスタムAPIで自分のPCのAIを使う場合は、キーも費用も要りません。</li>
        <li>実行前の費用は目安です。実際の請求は各社の管理画面で確認してください。</li>
        <li>OpenRouterはログインするだけで使えます。発行されたキーはこのブラウザに保存します。</li>
        <li>APIキーを入力する場合は、このアプリ専用のものを作り、利用上限と期限を設定してください。共用のパソコンでは使わないでください。</li>
        <li>APIの利用には各社の規約が適用されます。AI各社の多くは18歳以上を利用条件にしているので、AI分析は18歳以上の方がご利用ください。カスタムAPIで使うモデルには、そのモデルのライセンスが適用されます。</li>
      </ul>

      <h2>本人確認</h2>
      <p>
        他の人のアカウントをAIに評価させることを防ぐため、AI分析の前に、NIP-07対応の拡張機能(nos2x、Albyなど)か、NIP-46対応の署名アプリ(Amberなど)で本人確認をします。秘密鍵をこのアプリに渡すことはありません。本人確認の署名はこのブラウザの中で確かめるだけで、公開はしません。署名アプリとの連絡には、リレーを通して暗号化した通信を使います。
      </p>

      <h2>分析結果について</h2>
      <ul>
        <li>結果は投稿をもとにAIが作った推定と創作で、事実とは限りません。内容をうのみにせず、事実確認をしてください。</li>
        <li>診断書、鑑定書、賞状などは架空のもので、実在の組織や資格とは関係ありません。</li>
        <li>IQ、精神年齢、診断名などは娯楽であり、知能検査や医学的、心理学的な診断ではありません。</li>
        <li>結果を共有するときは、他の人の投稿や話題が含まれていないか確認してください。</li>
      </ul>

      <h2>取得できる投稿の限界</h2>
      <p>リレーに残っている分しか取得できません。古い投稿が欠けていることがあり、TLは現在のフォローをもとに再現します。</p>

      <h2>データの削除</h2>
      <p>設定の「全削除」で、このブラウザからすべて消せます。別のアカウントを使うときも全削除してください。</p>

      <h2>免責</h2>
      <p>
        このアプリは現状のまま提供します。利用によって生じた損害や費用について、運営者は責任を負いません。Nostrの開発者、Anthropic、OpenAI、Google、OpenRouterとは関係ありません。
      </p>

      {(SITE.operator || SITE.contact || SITE.sourceUrl) && (
        <>
          <h2>運営者</h2>
          {SITE.operator && <p>{SITE.operator}</p>}
          {SITE.contact && <p>連絡先: {SITE.contact}</p>}
          {SITE.sourceUrl && (
            <p>
              <a href={SITE.sourceUrl} target="_blank" rel="noreferrer">
                ソースコード
              </a>
            </p>
          )}
        </>
      )}
    </section>
  )
}
